#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# ///
"""Generate a pi-agent ``models.json`` from this project's ``config.yaml``.

Pi looks up models in ``~/.pi/agent/models.json``. To avoid hand-maintaining
that file as the model set grows, this script derives the same shape from
``config.yaml`` (the source of truth generated by ``build-config.py``).

The emitted file lists one provider per host (named after the local hostname)
containing every entry registered with llama-swap. Optional flags let you
preview the file or override fields.

Usage:
    ./bin/pi-models.py                     # write pi-models.json
    ./bin/pi-models.py --stdout            # print to stdout
    ./bin/pi-models.py --base-url URL      # override the base URL

Reasoning rule:
    A model is reported as non-reasoning only when the recipe disabled
    thinking (``--chat-template-kwargs '{"enable_thinking":false}'``) or the
    entry id contains the literal token ``instruct``. Otherwise it is
    reasoning-capable, regardless of guardrail variants like ``heretic``.

Output path defaults to ``./pi-models.json``. The companion ``make pi-install``
target copies the file to ``~/.pi/agent/models.json``.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import socket
import sys
from pathlib import Path

DEFAULT_BASE_URL = "http://127.0.0.1:8080/v1"
DEFAULT_CONTEXT_WINDOW = 131072
DEFAULT_MAX_TOKENS = 16384
FALLBACK_PROVIDER_NAME = "llama-swap"

# Matches ``--fit-ctx N`` in a llama-server command line. We pick the LAST
# occurrence in case some recipe repeats the flag, and we tolerate spaces
# around the equals sign.
FIT_CTX_RE = re.compile(r"--fit-ctx(?:=|\s+)(\d+)")
MMPROJ_RE = re.compile(r"(?m)(?:^|\s)--mmproj(?:\s|\=)")
CHAT_TEMPLATE_KWARGS_RE = re.compile(r"--chat-template-kwargs\s+'([^']+)'")
INSTRUCT_TOKEN = "instruct"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate pi-agent models.json from config.yaml.",
    )
    parser.add_argument(
        "--config",
        default="config.yaml",
        help="Path to llama-swap config.yaml (default: ./config.yaml).",
    )
    parser.add_argument(
        "--output",
        default="pi-models.json",
        help="Output file (default: ./pi-models.json). Use --stdout to skip.",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="Write the JSON to stdout instead of a file.",
    )
    parser.add_argument(
        "--base-url",
        default=None,
        help="Override the provider base URL (default: see resolution order).",
    )
    parser.add_argument(
        "--hostname",
        default=None,
        help="Override the hostname used to name the provider.",
    )
    return parser.parse_args()


def sanitize_provider_name(name: str) -> str:
    """Lowercase, replace non-alphanumerics with '-', collapse repeats."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug or FALLBACK_PROVIDER_NAME


def resolve_hostname(explicit: str | None) -> str:
    if explicit:
        return sanitize_provider_name(explicit)
    try:
        return sanitize_provider_name(socket.gethostname())
    except OSError:
        return FALLBACK_PROVIDER_NAME


def resolve_base_url(explicit: str | None) -> str:
    if explicit:
        return explicit.rstrip("/") + "/v1" if not explicit.endswith("/v1") else explicit
    for env in ("PI_BASE_URL", "LLAMA_BASE_URL"):
        value = os.environ.get(env)
        if value:
            return value.rstrip("/") + "/v1" if not value.endswith("/v1") else value
    return DEFAULT_BASE_URL


def strip_quotes(value: str) -> str:
    """Remove one layer of surrounding single or double quotes if present."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
        return value[1:-1]
    return value


def read_yaml_scalar(text: str, key: str) -> str | None:
    """Read a top-level ``key: value`` scalar from a tiny YAML subset.

    ``config.yaml`` is hand-emitted by ``build-config.py``. The top-level
    ``name:`` lines we care about are simple ``key: "value"`` or
    ``key: value`` scalars. Anything we cannot parse confidently returns
    ``None`` rather than raising, since the script must tolerate future
    format changes gracefully.
    """
    pattern = re.compile(rf'(?m)^[\s\-]*{re.escape(key)}:\s*(.+?)\s*$')
    match = pattern.search(text)
    if not match:
        return None
    return strip_quotes(match.group(1))


def parse_models_section(text: str) -> list[tuple[str, dict]]:
    """Extract ``models:`` entries (id + name + cmd) from config.yaml.

    Returns a list of ``(entry_id, {"name": str, "cmd": str})`` tuples in
    document order. This is a deliberately small YAML reader that only
    handles the structure emitted by build-config.py:

        models:
          entry-id:
            name: "display name"
            cmd: |
              /path/to/llama-server \\
                --model ... \\
                --mmproj ... \\
                -ctk q8_0 -ctv q8_0 --fit-ctx 131072 ...
            proxy: "http://127.0.0.1:${PORT}"
            ttl: 0
    """
    entries: list[tuple[str, dict]] = []
    lines = text.splitlines()
    in_models = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if not in_models:
            if re.match(r"^models:\s*$", line):
                in_models = True
            i += 1
            continue

        # End of the models block: a non-blank, non-indented line.
        if line and not line.startswith(" "):
            break

        # Entry header: "  entry-id:".
        header = re.match(r"^  ([A-Za-z0-9_\-.]+):\s*$", line)
        if not header:
            i += 1
            continue
        entry_id = header.group(1)
        name: str | None = None
        cmd: list[str] = []
        i += 1
        in_cmd = False
        while i < len(lines):
            sub = lines[i]
            # Next entry or end of the models block.
            if sub.startswith("  ") and not sub.startswith("    "):
                break
            if sub and not sub.startswith(" "):
                break
            if in_cmd:
                # Cmd literal block: lines indented with at least four spaces.
                if sub.startswith("    "):
                    cmd.append(sub[4:].rstrip())
                    i += 1
                    continue
                in_cmd = False
                # fall through to scalar parsing
            name_match = re.match(r'^    name:\s*(.+?)\s*$', sub)
            cmd_match = re.match(r"^    cmd:\s*\|\s*$", sub)
            if name_match:
                name = strip_quotes(name_match.group(1))
                i += 1
                continue
            if cmd_match:
                in_cmd = True
                i += 1
                continue
            i += 1

        joined_cmd = "\n".join(cmd)
        entries.append((entry_id, {"name": name or entry_id, "cmd": joined_cmd}))

    return entries


def parse_chat_template_kwargs(cmd: str) -> dict:
    """Return the parsed --chat-template-kwargs JSON object, or {} if absent."""
    match = CHAT_TEMPLATE_KWARGS_RE.search(cmd)
    if not match:
        return {}
    try:
        return json.loads(match.group(1))
    except json.JSONDecodeError:
        return {}


def context_window_from_cmd(cmd: str) -> int:
    matches = FIT_CTX_RE.findall(cmd)
    if matches:
        try:
            return int(matches[-1])
        except ValueError:
            pass
    return DEFAULT_CONTEXT_WINDOW


def has_mmproj(cmd: str) -> bool:
    return bool(MMPROJ_RE.search(cmd))


def reasoning_for(entry_id: str, cmd: str) -> bool:
    """False only when thinking is explicitly disabled or the id says instruct."""
    ctk = parse_chat_template_kwargs(cmd)
    if ctk.get("enable_thinking") is False:
        return False
    if INSTRUCT_TOKEN in entry_id.lower():
        return False
    return True


def build_model(entry_id: str, name: str, cmd: str) -> dict:
    model: dict = {
        "id": entry_id,
        "name": name,
        "input": ["text", "image"] if has_mmproj(cmd) else ["text"],
        "contextWindow": context_window_from_cmd(cmd),
        "maxTokens": DEFAULT_MAX_TOKENS,
        "reasoning": reasoning_for(entry_id, cmd),
        "cost": {"input": 0, "output": 0, "cacheRead": 0, "cacheWrite": 0},
    }
    return model


def build_provider(args: argparse.Namespace) -> dict:
    text = Path(args.config).read_text()
    entries = parse_models_section(text)
    provider_name = resolve_hostname(args.hostname)
    base_url = resolve_base_url(args.base_url)
    return {
        "providers": {
            provider_name: {
                "baseUrl": base_url,
                "api": "openai-completions",
                "apiKey": "local",
                "compat": {
                    "supportsDeveloperRole": False,
                    "supportsReasoningEffort": False,
                    "maxTokensField": "max_tokens",
                },
                "models": [build_model(eid, data["name"], data["cmd"]) for eid, data in entries],
            }
        }
    }


def _write_if_changed(path: Path, payload: str) -> bool:
    """Write ``payload`` to ``path`` only if the existing contents differ.

    Preserves the existing mtime on no-op runs so consumers that watch the
    file (or that may have already copied it elsewhere) are not triggered
    by a spurious timestamp change. Returns True when a write occurred.
    """
    try:
        existing = path.read_text()
    except FileNotFoundError:
        path.write_text(payload)
        return True
    if existing == payload:
        return False
    path.write_text(payload)
    return True


def main() -> int:
    args = parse_args()
    provider = build_provider(args)
    payload = json.dumps(provider, indent=2, sort_keys=True) + "\n"
    if args.stdout:
        sys.stdout.write(payload)
        return 0
    output = Path(args.output).expanduser()
    if not output.is_absolute():
        output = (Path.cwd() / output).resolve()
    provider_name = next(iter(provider["providers"]))
    if _write_if_changed(output, payload):
        print(f"wrote {output}", file=sys.stderr)
    else:
        print(f"unchanged {output}", file=sys.stderr)
    print(f"  provider: {provider_name}", file=sys.stderr)
    print(f"  models:   {len(provider['providers'][provider_name]['models'])}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
